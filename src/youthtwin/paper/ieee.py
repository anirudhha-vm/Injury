def sim_growth(run: Path | None, values: Values) -> str:
    names = [
        "SimGrowthN",
        "SimTwinMAE",
        "SimMooreMAE",
        "SimCoverage",
        "SimCoverageNear",
        "SimCoverageFar",
    ]
