"""LaTeX values and tables for the IEEE manuscript, generated from run outputs.

``paper/ieee/main.tex`` contains prose and macros only; every number it prints comes from the
files written here into ``paper/tables/`` (each with a provenance sidecar naming its runs):

- ``ieee_values.tex``: one ``\\newcommand`` per number, with the run ID in a comment;
- ``ieee_tab_*.tex``: complete ``tabular`` environments.

A value whose run does not exist yet expands to a visible red ``[pending]`` marker, so a draft
compiled early cannot pass for a finished one.
"""

from __future__ import annotations

import json
import math
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import pandas as pd

PRIMARY = "time_dependent_auc_4wk"
PENDING = r"\textcolor{red}{[pending]}"
BANDS = ("more than 3 before", "3 to 1 before", "within 1", "1 to 3 after", "more than 3 after")
GROUPS = ("pre_phv", "circa_phv", "post_phv")
GROUP_LABEL = {"pre_phv": "Pre-PHV", "circa_phv": "Circa-PHV", "post_phv": "Post-PHV"}


def _number(value: Any, digits: int) -> str:
    if hasattr(value, "item"):
        value = value.item()
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    if isinstance(value, int):
        return f"{value:,}".replace(",", "{,}")
    text = f"{float(value):.{digits}f}"
    return text.replace("-", "$-$") if text.startswith("-") else text


def percent(value: Any, digits: int = 0) -> str:
    """A proportion as a LaTeX percentage."""
    if hasattr(value, "item"):
        value = value.item()
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    return f"{100.0 * float(value):.{digits}f}\\%"


@dataclass
class Values:
    """Collected macros and the runs they came from."""

    macros: dict[str, tuple[str, str]] = field(default_factory=dict)  # name -> (text, source)
    runs: dict[str, str] = field(default_factory=dict)  # kind -> run_id

    def put(self, name: str, text: str, source: str) -> None:
        if not name.isalpha():
            raise ValueError(f"LaTeX macro names must be letters only: {name}")
        self.macros[name] = (text, source)

    def number(self, name: str, value: Any, source: str, digits: int = 2) -> None:
        self.put(name, _number(value, digits), source)

    def pending(self, *names: str) -> None:
        for name in names:
            self.macros.setdefault(name, (PENDING, "pending"))

    def render(self) -> str:
        lines = ["% Generated by scripts/build_paper.py. Do not edit: rerun the analysis."]
        for name, (text, source) in sorted(self.macros.items()):
            lines.append(
                f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{text}}}% {source}"
            )
        return "\n".join(lines) + "\n"


def run_id(run: Path) -> str:
    return str(json.loads((run / "run.json").read_text(encoding="utf-8"))["run_id"])


def _record(run: Path) -> dict[str, Any]:
    record: dict[str, Any] = json.loads((run / "run.json").read_text(encoding="utf-8"))
    return record


def tabular(
    columns: str, header: list[str], rows: list[list[str]], groups: list[int] | None = None
) -> str:
    """A booktabs tabular; ``groups`` are row indices before which a midrule is drawn."""
    lines = [
        f"\\begin{{tabular}}{{{columns}}}",
        "\\toprule",
        " & ".join(header) + r" \\",
        "\\midrule",
    ]
    for k, row in enumerate(rows):
        if groups and k in groups and k > 0:
            lines.append("\\midrule")
        lines.append(" & ".join(row) + r" \\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def pending_table(columns: int, what: str) -> str:
    return tabular(
        "l" * columns, [f"\\multicolumn{{{columns}}}{{l}}{{{PENDING} {what}}}"] + [""] * 0, []
    )


# --------------------------------------------------------------------------- real growth


def real_growth(run: Path | None, values: Values) -> str:
    names = [
        "BerkIncluded",
        "BerkChildren",
        "BerkStrict",
        "BerkReplicates",
        "BerkTwinMAE",
        "BerkMooreMAE",
        "BerkMirwaldMAE",
        "BerkTwinBias",
        "BerkMooreBias",
        "BerkCoverage",
        "BerkWidth",
        "BerkCoverageNear",
        "BerkTwinMAENear",
        "BerkMooreMAENear",
        "BerkCoverageFar",
        "BerkStrictTwinMAE",
        "BerkStrictMooreMAE",
        "BerkStrictCoverage",
        "BerkRhat",
        "BerkESS",
        "BerkGirlsAPHV",
        "BerkBoysAPHV",
        "BerkWindows",
    ]
    if run is None:
        values.pending(*names)
        return pending_table(8, "Berkeley growth study")
    rid = run_id(run)
    values.runs["real_growth_berkeley"] = rid
    summary = pd.read_csv(run / "summary.csv")
    reference = pd.read_csv(run / "reference.csv")
    scores = pd.read_csv(run / "per_athlete.csv")
    record = _record(run)
    included = reference[reference["included"]]
    values.number("BerkIncluded", len(included), rid)
    values.number("BerkChildren", len(reference), rid)
    values.number("BerkStrict", int(scores.loc[scores["strict"], "athlete_id"].nunique()), rid)
    values.number("BerkReplicates", int(scores["replicate"].nunique()), rid)
    values.number("BerkWindows", len(scores), rid)
    for sex, name in (("female", "BerkGirlsAPHV"), ("male", "BerkBoysAPHV")):
        values.number(
            name, float(included.loc[included["sex"] == sex, "reference_aphv"].mean()), rid, 1
        )
    full = summary[summary["reference_subset"] == "all"]
    overall = full[full["grouping"] == "all"].iloc[0]
    values.number("BerkTwinMAE", overall["posterior_mae_years"], rid)
    values.number("BerkMooreMAE", overall["point_mae_years"], rid)
    values.number("BerkMirwaldMAE", overall["mirwald_mae_years"], rid)
    values.number("BerkTwinBias", overall["posterior_bias_years"], rid)
    values.number("BerkMooreBias", overall["point_bias_years"], rid)
    values.put("BerkCoverage", percent(overall["coverage"]), rid)
    values.number("BerkWidth", overall["mean_interval_width_years"], rid)
    near = scores[scores["years_from_phv"].abs() <= 3.0]
    far = scores[scores["years_from_phv"].abs() > 3.0]
    values.put("BerkCoverageNear", percent(near["covered"].mean()), rid)
    values.put("BerkCoverageFar", percent(far["covered"].mean()), rid)
    values.number("BerkTwinMAENear", near["posterior_abs_error"].mean(), rid)
    values.number("BerkMooreMAENear", near["point_abs_error"].mean(), rid)
    strict = summary[
        (summary["reference_subset"] == "strict reference") & (summary["grouping"] == "all")
    ].iloc[0]
    values.number("BerkStrictTwinMAE", strict["posterior_mae_years"], rid)
    values.number("BerkStrictMooreMAE", strict["point_mae_years"], rid)
    values.put("BerkStrictCoverage", percent(strict["coverage"]), rid)
    fits = record.get("fits", {})
    values.number("BerkRhat", max(float(f["max_rhat"]) for f in fits.values()), rid)
    values.number("BerkESS", int(min(float(f["min_ess_bulk"]) for f in fits.values())), rid)

    rows = []
    order = (
        [("all", "all", "All")]
        + [("sex", s, s.capitalize()) for s in ("female", "male")]
        + [
            ("band", b, b.replace("more than", "$>$").replace(" to ", "--").capitalize())
            for b in BANDS
        ]
    )
    for grouping, group, label in order:
        match = full[(full["grouping"] == grouping) & (full["group"].astype(str) == group)]
        if match.empty:
            continue
        r = match.iloc[0]
        rows.append(
            [
                label,
                _number(int(r["n_athletes"]), 0),
                _number(r["posterior_mae_years"], 2),
                _number(r["point_mae_years"], 2),
                _number(r["mirwald_mae_years"], 2),
                _number(r["posterior_bias_years"], 2),
                _number(r["point_bias_years"], 2),
                percent(r["coverage"]),
                _number(r["mean_interval_width_years"], 2),
            ]
        )
    header = [
        "Group",
        "$n$",
        "Twin",
        "Moore",
        "Mirwald",
        "Twin bias",
        "Moore bias",
        "Coverage",
        "Width",
    ]
    return tabular("lrrrrrrrr", header, rows, groups=[1, 3])


# --------------------------------------------------------------------------- real risk


def real_risk(run: Path | None, values: Values) -> str:
    names = [
        "RunRunners",
        "RunRows",
        "RunInjuries",
        "RunAucLogit",
        "RunAucLogitCI",
        "RunAucBoost",
        "RunAucBoostCI",
        "RunAucLoad",
        "RunAucLoadCI",
        "RunSlopeLoad",
        "RunSlopeLogit",
        "RunSlopeBoost",
        "RunTempAucLogit",
        "RunTempSlopeLogit",
        "RunDiffLogit",
        "RunDiffLogitCI",
        "RunInflBoost",
        "RunInflBoostCI",
        "RunInflLogit",
        "RunInflLogitCI",
        "RunInflLoad",
        "RunInflLoadCI",
    ]
    if run is None:
        values.pending(*names)
        return pending_table(4, "runners' injury study")
    rid = run_id(run)
    values.runs["real_risk_runners"] = rid
    performance = pd.read_csv(run / "performance.csv")
    differences = pd.read_csv(run / "differences.csv")
    inflation = pd.read_csv(run / "leakage_inflation.csv").set_index("model")
    first = performance.iloc[0]
    values.number("RunRunners", int(first["n_athletes"]), rid)
    values.number("RunRows", int(first["n_rows"]), rid)
    values.number("RunInjuries", int(first["n_events"]), rid)

    def cell(scheme: str, model: str, metric: str) -> pd.Series:
        return performance[
            (performance["scheme"] == scheme)
            & (performance["model"] == model)
            & (performance["metric"] == metric)
        ].iloc[0]

    def ci(r: pd.Series, digits: int = 2) -> str:
        return f"{_number(r['ci_low'], digits)}--{_number(r['ci_high'], digits)}"

    for model, tag in (
        ("penalised_logistic", "Logit"),
        ("gradient_boosting", "Boost"),
        ("load_only", "Load"),
    ):
        r = cell("runner_grouped", model, PRIMARY)
        values.number(f"RunAuc{tag}", r["estimate"], rid)
        values.put(f"RunAuc{tag}CI", ci(r), rid)
        values.number(
            f"RunSlope{tag}", cell("runner_grouped", model, "calibration_slope")["estimate"], rid
        )
    values.number(
        "RunTempAucLogit", cell("temporal_holdout", "penalised_logistic", PRIMARY)["estimate"], rid
    )
    values.number(
        "RunTempSlopeLogit",
        cell("temporal_holdout", "penalised_logistic", "calibration_slope")["estimate"],
        rid,
    )
    d = differences[
        (differences["model"] == "penalised_logistic") & (differences["metric"] == PRIMARY)
    ].iloc[0]
    values.number("RunDiffLogit", d["difference"], rid)
    values.put("RunDiffLogitCI", f"{_number(d['ci_low'], 2)}--{_number(d['ci_high'], 2)}", rid)
    for model, tag in (
        ("gradient_boosting", "Boost"),
        ("penalised_logistic", "Logit"),
        ("load_only", "Load"),
    ):
        infl = inflation.loc[model]
        values.number(f"RunInfl{tag}", infl["leaky_minus_grouped"], rid, 3)
        values.put(
            f"RunInfl{tag}CI", f"{_number(infl['ci_low'], 3)}--{_number(infl['ci_high'], 3)}", rid
        )

    rows: list[list[str]] = []
    groups: list[int] = []
    schemes = {
        "runner_grouped": "Runner-grouped CV",
        "temporal_holdout": "Temporal hold-out",
        "row_level_leaky": "Row-level CV (leaky)",
    }
    models = {
        "load_only": "Load only",
        "penalised_logistic": "Penalised logistic",
        "gradient_boosting": "Gradient boosting",
    }
    for scheme, scheme_label in schemes.items():
        groups.append(len(rows))
        for model, model_label in models.items():
            auc, slope = cell(scheme, model, PRIMARY), cell(scheme, model, "calibration_slope")
            rows.append(
                [
                    scheme_label if model == "load_only" else "",
                    model_label,
                    f"{_number(auc['estimate'], 2)} ({ci(auc)})",
                    f"{_number(slope['estimate'], 2)} ({ci(slope)})",
                ]
            )
    return tabular(
        "llrr", ["Split", "Model", "AUC (95\\% CI)", "Calibration slope (95\\% CI)"], rows, groups
    )


# --------------------------------------------------------------------------- validity


def validity(run: Path | None, values: Values) -> str:
    names = [
        "ValOffset",
        "ValStudies",
        "ValKneeRMSEPre",
        "ValKneeRMSEPost",
        "ValFppaRMSEPre",
        "ValFppaRMSEPost",
        "ValFppaRMSECirca",
        "ValFppaPassPre",
        "ValFppaPassCirca",
        "ValFppaPassPost",
        "ValKneePassMin",
        "ValFppaICCPre",
        "ValFppaICCPost",
    ]
    if run is None:
        values.pending(*names)
        return pending_table(7, "validity simulation")
    rid = run_id(run)
    values.runs["sim_study_validation"] = rid
    record = _record(run)
    agreement = pd.read_csv(run / "agreement_by_maturity_group.csv")
    precision = pd.read_csv(run / "precision.csv")
    values.number("ValOffset", float(record["calibrated_offset_sd_px"]), rid, 1)
    values.number("ValStudies", int(precision["n_studies"].max()), rid)

    def prec(variable: str, event: str, group: str) -> pd.Series:
        return precision[
            (precision["variable"] == variable)
            & (precision["event"] == event)
            & (precision["maturity_group"] == group)
        ].iloc[0]

    def agree(variable: str, event: str, group: str) -> pd.Series:
        return agreement[
            (agreement["variable"] == variable)
            & (agreement["event"] == event)
            & (agreement["maturity_group"] == group)
        ].iloc[0]

    values.number("ValKneeRMSEPre", prec("knee_flexion", "max", "pre_phv")["rmse_mean"], rid, 1)
    values.number("ValKneeRMSEPost", prec("knee_flexion", "max", "post_phv")["rmse_mean"], rid, 1)
    for group, tag in (("pre_phv", "Pre"), ("circa_phv", "Circa"), ("post_phv", "Post")):
        p = prec("knee_fppa", "peak_knee_flexion", group)
        values.number(f"ValFppaRMSE{tag}", p["rmse_mean"], rid, 1)
        values.put(f"ValFppaPass{tag}", percent(p["share_studies_meeting_threshold"]), rid)
    knee = precision[(precision["variable"] == "knee_flexion")]
    values.put("ValKneePassMin", percent(knee["share_studies_meeting_threshold"].min()), rid)
    values.number("ValFppaICCPre", agree("knee_fppa", "peak_knee_flexion", "pre_phv")["icc21"], rid)
    values.number(
        "ValFppaICCPost", agree("knee_fppa", "peak_knee_flexion", "post_phv")["icc21"], rid
    )

    rows: list[list[str]] = []
    groups: list[int] = []
    variables = (
        ("knee_flexion", "max", "Peak knee flexion"),
        ("knee_fppa", "peak_knee_flexion", "Knee FPPA at peak flexion"),
        ("knee_fppa", "max", "Peak knee FPPA"),
        ("hip_flexion", "max", "Peak hip flexion"),
    )
    for variable, event, label in variables:
        groups.append(len(rows))
        for group in GROUPS:
            a, p = agree(variable, event, group), prec(variable, event, group)
            rows.append(
                [
                    label if group == "pre_phv" else "",
                    GROUP_LABEL[group],
                    _number(a["bias"], 1),
                    f"{_number(a['loa_low'], 1)} to {_number(a['loa_high'], 1)}",
                    _number(a["icc21"], 2),
                    f"{_number(p['rmse_mean'], 1)} ({_number(p['rmse_p025'], 1)}--{_number(p['rmse_p975'], 1)})",
                    percent(p["share_studies_meeting_threshold"]),
                ]
            )
    header = [
        "Variable",
        "Maturity",
        "Bias",
        "95\\% LoA",
        "ICC",
        "RMSE, mean (range)",
        "RMSE $<$ limit",
    ]
    return tabular("llrrrrr", header, rows, groups)


