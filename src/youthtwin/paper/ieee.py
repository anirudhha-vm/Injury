def sim_risk(run: Path | None, values: Values) -> str:
    names = [
        "SimAthletes",
        "SimEventWeeks",
        "SimConfPredictors",
        "SimConfAuc",
        "SimConfAucCI",
        "SimLogitAuc",
        "SimLogitAucCI",
        "SimBoostAuc",
        "SimConfSlope",
        "SimLogitSlope",
        "SimDiffCount",
        "SimDiffExcludingZero",
        "SimPrevalence",
    ]
    if run is None:
        values.pending(*names)
        return pending_table(3, "simulated risk models")
    rid = run_id(run)
    values.runs["evaluation"] = rid
    performance = pd.read_csv(run / "performance.csv")
    record = _record(run)
    first = performance.iloc[0]
    values.number("SimAthletes", int(first["n_athletes"]), rid)
    values.number("SimEventWeeks", int(first["n_events"]), rid)
    differences = pd.read_csv(run / "differences.csv")
    auc_differences = differences[differences["metric"] == PRIMARY]
    values.number("SimDiffCount", len(auc_differences), rid)
    values.number("SimDiffExcludingZero", int(auc_differences["interval_excludes_zero"].sum()), rid)
    values.put(
        "SimPrevalence", percent(record["person_period"]["prevalence"]["y_growth_related"], 2), rid
    )
    chosen = record.get("confirmatory_predictors") or []
    values.put("SimConfPredictors", ", ".join(c.replace("_", r"\_") for c in chosen) or "none", rid)

    def cell(model: str, metric: str) -> pd.Series | None:
        match = performance[(performance["model"] == model) & (performance["metric"] == metric)]
        return None if match.empty else match.iloc[0]

    for model, tag in (
        ("confirmatory", "Conf"),
        ("hazard_logit", "Logit"),
        ("hazard_xgb", "Boost"),
    ):
        auc, slope = cell(model, PRIMARY), cell(model, "calibration_slope")
        if auc is None or slope is None:
            values.pending(f"Sim{tag}Auc", f"Sim{tag}AucCI", f"Sim{tag}Slope")
            continue
        values.number(f"Sim{tag}Auc", auc["estimate"], rid)
        values.put(
            f"Sim{tag}AucCI", f"{_number(auc['ci_low'], 2)}--{_number(auc['ci_high'], 2)}", rid
        )
        values.number(f"Sim{tag}Slope", slope["estimate"], rid)
    labels = {
        "age_only": "Age only",
        "maturity_growth_velocity": "Maturity + growth velocity",
        "screening_only": "Screening only",
        "confirmatory": "Confirmatory (Riley-sized)",
        "hazard_logit": "Penalised logistic hazard",
        "hazard_xgb": "Boosted hazard",
    }
    rows = []
    for model, label in labels.items():
        auc, slope = cell(model, PRIMARY), cell(model, "calibration_slope")
        if auc is None or slope is None:
            continue
        rows.append(
            [
                label,
                f"{_number(auc['estimate'], 2)} ({_number(auc['ci_low'], 2)}--{_number(auc['ci_high'], 2)})",
                f"{_number(slope['estimate'], 2)} ({_number(slope['ci_low'], 2)}--{_number(slope['ci_high'], 2)})",
            ]
        )
    return tabular("lrr", ["Model", "AUC (95\\% CI)", "Calibration slope (95\\% CI)"], rows)


def ablation(run: Path | None, values: Values) -> str:
    names = [
        "AblFilmVsConcat",
        "AblFilmVsConcatCI",
        "AblFilmVsLate",
        "AblFilmVsLateCI",
        "AblFilmVsNone",
        "AblFilmVsNoneCI",
        "AblCoverage",
    ]
    if run is None or not (run / "differences.csv").is_file():
        values.pending(*names)
        return pending_table(4, "ablation")
    rid = run_id(run)
    values.runs["ablation"] = rid
    results = pd.read_csv(run / "results.csv")
    differences = pd.read_csv(run / "differences.csv")
    wide = results.pivot_table(
        index=["ablation_id", "name"], columns="metric", values="value"
    ).reset_index()
    for reference, tag in (
        ("concat_v2_design", "Concat"),
        ("late_fusion", "Late"),
        ("movement_encoder_only", "None"),
    ):
        d = differences[
            (differences["model"] == "film_proposed")
            & (differences["reference"] == reference)
            & (differences["metric"] == PRIMARY)
        ]
        if d.empty:
            values.pending(f"AblFilmVs{tag}", f"AblFilmVs{tag}CI")
            continue
        r = d.iloc[0]
        values.number(f"AblFilmVs{tag}", r["difference"], rid, 3)
        values.put(
            f"AblFilmVs{tag}CI", f"{_number(r['ci_low'], 3)} to {_number(r['ci_high'], 3)}", rid
        )
    if "interval_coverage_of_true_risk" in wide.columns:
        values.put(
            "AblCoverage", percent(wide["interval_coverage_of_true_risk"].dropna().iloc[0]), rid
        )
    else:
        values.pending("AblCoverage")
    rows = [
        [
            str(int(r["ablation_id"])),
            str(r["name"]).replace("_", " "),
            _number(r["auc"], 3),
            _number(r.get("correlation_with_true_risk", float("nan")), 2),
        ]
        for _, r in wide.iterrows()
    ]
    return tabular("rlrr", ["\\#", "Configuration", "AUC", "Corr.\\ with true risk"], rows)


def propagation(run: Path | None, values: Values) -> str:
    """Growth-uncertainty propagation (configurations 8 and 9 with growth-twin posteriors)."""
    names = [
        "PropAthletes",
        "PropEnsemble",
        "PropDraws",
        "PropCoverage",
        "PropWidth",
        "PropSD",
        "PropRisk",
        "PropAucWith",
        "PropAucWithout",
        "PropCorrWith",
        "PropCorrWithout",
        "PropDiff",
        "PropDiffCI",
    ]
    if run is None:
        values.pending(*names)
        return ""
    rid = run_id(run)
    values.runs["ablation_propagation"] = rid
    results = pd.read_csv(run / "results.csv")
