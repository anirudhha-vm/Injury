"""Draft the methods text from the configuration files (brief M9: "from configs, not memory").

Every value that the pipeline actually uses is read from ``configs/`` and written inside a
``[[SPEC: ...]]`` tag, so the methods section cannot drift from the code: a test regenerates
the draft and compares it with the committed file. Results never appear here; they are
``[[RESULT: ...]]`` placeholders in the outlines until a run fills them.

The text is a scaffold for the authors to rewrite, not finished prose. Statements that need a
human decision or check carry ``TODO(human)``.
"""

