HEADER = (
    "<!-- GENERATED by scripts/draft_methods.py from configs/. Do not edit by hand: change the "
    "config and regenerate. -->"
)


def spec(value: Any) -> str:
    """A design value in the tag the results guard accepts."""
    if isinstance(value, bool):
        text = "yes" if value else "no"
    elif isinstance(value, (list, tuple)):
        text = ", ".join(str(v) for v in value)
    else:
        text = str(value)
    return f"[[SPEC: {text}]]"


def _names(values: Sequence[str]) -> str:
    return ", ".join(str(v).replace("_", " ") for v in values)


def load_all() -> dict[str, dict[str, Any]]:
    return {name: load_config(path) for name, path in CONFIG_FILES.items()}


